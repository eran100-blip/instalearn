import json, hashlib, os
from build import ALL
def js(x): return json.dumps(x, ensure_ascii=False)
out = []
out.append('''// AUTO-GENERATED by the clip pipeline (clips/codegen.py) – edit the content there, not here.
// Every video is a 15-second original animated clip stored in assets/videos.

export type Question = {
  id: string;
  level: 1 | 2 | 3; // 1 = easy, 2 = medium, 3 = hard
  type: 'mcq' | 'truefalse';
  prompt: string;
  options: string[];
  correctIndex: number;
  explanation: string;
};

export type LearningVideo = {
  id: string;
  title: string;
  subtitle?: string; // e.g. the Latin / English term for Hebrew videos
  courseId: string; // matches an id in data/courses.ts
  topic: string;
  lang: 'en' | 'he';
  creator: string;
  video: number; // require()'d local mp4
  likes: number;
  definition: string; // short definition (also burned into the clip)
  explanation: string; // full explanation, shown in "Read more"
  tip?: string; // memory tip
  // One question per difficulty level. The feed picks the one that matches
  // the level the student chose for this course in Settings.
  questions: Question[];
};

export const VIDEOS: LearningVideo[] = [''')
for v in ALL:
    likes = 300 + int(hashlib.md5(v['id'].encode()).hexdigest()[:4], 16) % 2500
    qs = []
    for q in v['questions']:
        qs.append({k: q[k] for k in ['id', 'level', 'type', 'prompt', 'options', 'correctIndex', 'explanation']})
    lines = [f"  {{",
             f"    id: {js(v['id'])},",
             f"    title: {js(v['title'])},"]
    if v.get('subtitle'): lines.append(f"    subtitle: {js(v['subtitle'])},")
    lines += [f"    courseId: {js(v['courseId'])},",
              f"    topic: {js(v['topic'])},",
              f"    lang: {js(v['lang'])},",
              f"    creator: 'InstaLearn',",
              f"    video: require('../../assets/videos/{v['id']}.mp4'),",
              f"    likes: {likes},",
              f"    definition: {js(v['definition'])},",
              f"    explanation: {js(v['explanation'])},"]
    if v.get('tip'): lines.append(f"    tip: {js(v['tip'])},")
    qj = json.dumps(qs, ensure_ascii=False, indent=2).replace('\n', '\n    ')
    lines.append(f"    questions: {qj},")
    lines.append("  },")
    out.append('\n'.join(lines))
out.append('''];

// Pick the question that matches the chosen level (0 = no question).
export function pickQuestion(video: LearningVideo, level: number): Question | null {
  if (level <= 0 || video.questions.length === 0) return null;
  const exact = video.questions.find((q) => q.level === level);
  if (exact) return exact;
  // Fall back to the closest level we have.
  return [...video.questions].sort(
    (a, b) => Math.abs(a.level - level) - Math.abs(b.level - level),
  )[0];
}

// True for Hebrew (right-to-left) text.
export function isRTL(text: string): boolean {
  return /[\\u0590-\\u05FF]/.test(text);
}
''')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src', 'data', 'sample.ts'), 'w', encoding='utf-8').write('\n'.join(out))
print('ok', len(ALL))
